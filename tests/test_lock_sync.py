"""The two lock files are the exact install, and they must not drift.

`requirements.txt` and `requirements-dev.txt` are the SPEC: loose `>=`
ranges, which say what the code needs. A spec is not a reproducible
install — a fresh clone on a later day silently resolves to whatever is
newest — so there was no known-good set to return to when an upstream
release broke something. The locks are that set:

    requirements.lock       the runtime closure, every package ==-pinned
    requirements-dev.lock   `-r requirements.lock` + the dev-only closure

Both are GENERATED by `tools/regen_lock.py` from the working `.venv`, and
this test fails when they no longer match it. Same reasoning as
`test_badges.py`: a file nobody checks stops being true by the next commit.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.regen_lock import LockFile, Requirements  # noqa: E402


class TestReadingASpec:
    def test_names_come_without_their_ranges_extras_or_includes(self):
        text = ("# comment\n-r requirements.txt\nfastapi>=0.110.0\n"
                "Pillow>=10.0   # covers\nuvicorn[standard]>=0.30\n\n")
        assert Requirements.names(text) == ["fastapi", "Pillow", "uvicorn"]

    def test_pins_skip_the_include_line(self):
        text = "# header\n-r requirements.lock\nh2==4.4.1\nruff==0.17.2        # direct\n"
        assert LockFile.pins(text) == ["h2==4.4.1", "ruff==0.17.2"]


class TestTheLocksAreTrue:
    @pytest.fixture(scope="class")
    def runtime(self):
        return LockFile.runtime()

    @pytest.fixture(scope="class")
    def dev(self):
        lock = LockFile.dev()
        if lock.missing_roots():
            pytest.skip(f"dev tools not installed: {lock.missing_roots()}")
        return lock

    def test_the_runtime_lock_matches_the_installed_closure(self, runtime):
        assert runtime.is_current(), (
            "requirements.lock is stale — run: .venv/bin/python tools/regen_lock.py")

    def test_the_dev_lock_matches_the_installed_closure(self, dev):
        assert dev.is_current(), (
            "requirements-dev.lock is stale — run: .venv/bin/python tools/regen_lock.py")

    def test_every_direct_dependency_is_locked(self, runtime):
        locked = {p.split("==")[0] for p in LockFile.pins(runtime.written())}
        missing = [n for n in runtime.roots() if Requirements.norm(n) not in locked]
        assert missing == []

    def test_every_pin_is_exact(self, runtime):
        loose = [p for p in LockFile.pins(runtime.written())
                 if not re.fullmatch(r"[\w.\-]+==[^=\s]+", p)]
        assert loose == []

    def test_the_dev_lock_includes_the_runtime_lock(self, dev):
        body = [ln.strip() for ln in dev.written().splitlines()
                if ln.strip() and not ln.lstrip().startswith("#")]
        assert body[0] == "-r requirements.lock"

    def test_no_package_is_pinned_in_both(self, runtime, dev):
        # One package, one pin: a shared dependency pinned twice can disagree.
        names = lambda lock: {p.split("==")[0] for p in LockFile.pins(lock.written())}  # noqa: E731
        assert names(runtime) & names(dev) == set()
