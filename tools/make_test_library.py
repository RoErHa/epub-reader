#!/usr/bin/env python3
# ruff: noqa: E402 — sys.path has to be set before these imports
"""Builds the fixture library the Playwright suite runs against.

Creates `.test-library/` with a plain book and a hostile, script-bearing
book, plus a `.env.test` pointing at it. Both are gitignored — this is
regenerated, never committed.
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tests.cbz_fixtures import CbzBuilder
from tests.epub_fixtures import EpubBuilder
from tests.mobi_fixtures import MobiBuilder, jpeg
from tests.pdf_fixtures import PdfBuilder, jpx

ENV_TEMPLATE = """# Generated by tools/make_test_library.py — do not edit.
EPUB_PORT={port}
EPUB_BIND=127.0.0.1
LIBRARY_ROOT={library}
DB_PATH=.test-library/books.db
COVER_CACHE=.test-library/covers
LOG_LEVEL=WARNING
LOG_FILE=.test-library/test.log
"""


class TestLibrary:
    PORT = 8771  # not 8770 — never collides with a running dev server

    def __init__(self, root: Path) -> None:
        self.root = root
        self.library = root / ".test-library" / "books"
        self.env_file = root / ".env.test"

    def build(self) -> None:
        self.library.mkdir(parents=True, exist_ok=True)
        # Everything, not just *.epub: the library serves five formats
        # now, and a renamed fixture that is never cleared away is a
        # test looking for a book that moved.
        for old in self.library.glob("*"):
            if old.is_file():
                old.unlink()
            else:
                shutil.rmtree(old)      # an unpacked book is a directory

        EpubBuilder(
            title="The Left Hand of Darkness",
            author="Ursula K. Le Guin",
            series="Hainish Cycle",
            series_index=4,
            subjects=["Science Fiction"],
            first_published="1969",
            chapters=4,
            paragraphs_per_chapter=6,
            cover=True,   # real books open on an image-only cover
        ).build(self.library / "left-hand-of-darkness.epub")

        # A comma in internal filenames breaks foliate's href resolution
        # (decodeURI leaves %2C alone). ~22% of the real library is like this.
        EpubBuilder(
            title="A Time to Die",
            author="John Vornholt",
            chapters=4,
            paragraphs_per_chapter=5,
            cover=True,
            filename_prefix="Vornholt, John - ",
            encode_nav_hrefs=True,
        ).build(self.library / "comma-filenames.epub")

        # One enormous single section, like the Donaldson EPUBs: 1.2 MB
        # in one document columnises into an ~8-million-pixel strip that
        # no browser can paint, so the reader must fall back to scrolled.
        EpubBuilder(
            title="One Huge Chapter",
            author="Stephen R. Donaldson",
            chapters=1,
            paragraphs_per_chapter=3000,
            cover=True,
        ).build(self.library / "huge-section.epub")

        # The detail-progress test opens a book, so it needs its own.
        EpubBuilder(
            title="Detail Progress Fixture", author="Test Author",
            chapters=3, paragraphs_per_chapter=4,
        ).build(self.library / "detail-progress.epub")

        # The "Reading now" shelf test opens a book, which writes
        # reading state — so it needs its own, like the position tests.
        EpubBuilder(
            title="Shelf Reading Fixture", author="Test Author",
            chapters=2, paragraphs_per_chapter=4,
        ).build(self.library / "shelf-reading.epub")

        # Marking a book read writes reading state exactly as opening one
        # does, so the finishing tests get their own book too. They reset
        # its status in beforeEach, the way the annotation tests clear
        # their marks — status can be set back, a position cannot.
        EpubBuilder(
            title="Finish Me", author="Test Author",
            chapters=2, paragraphs_per_chapter=3,
        ).build(self.library / "finish-me.epub")

        # Opening-position tests need books NOTHING else opens: any test
        # that opens a book saves a position, and a book with a saved
        # position correctly resumes instead of opening at the start.
        EpubBuilder(
            title="Start With Cover", author="Test Author",
            chapters=3, paragraphs_per_chapter=5, cover=True,
        ).build(self.library / "start-with-cover.epub")
        EpubBuilder(
            title="Start No Cover", author="Test Author",
            chapters=3, paragraphs_per_chapter=5,
        ).build(self.library / "start-no-cover.epub")

        # Reserved for the position tests. Opening a book WRITES reading
        # state, and position is shared server-side, so a position test
        # needs a book no other test opens — not merely one no other test
        # asserts on.
        for name in ("position-a.epub", "position-b.epub"):
            EpubBuilder(
                title=f"Position Fixture {name[9].upper()}",
                author="Test Author",
                chapters=4,
                paragraphs_per_chapter=5,
            ).build(self.library / name)

        # Reserved for the "never opened" assertion — position is shared
        # server-side (decision 7), so any book another test opens would
        # race it. Nothing else may open this one.
        EpubBuilder(
            title="A Wizard of Earthsea",
            author="Ursula K. Le Guin",
            subjects=["Fantasy"],
            first_published="1968",
            chapters=2,
            cover=True,
        ).build(self.library / "wizard-of-earthsea.epub")

        EpubBuilder(
            title="Untouched",
            author="Nobody",
            chapters=2,
        ).build(self.library / "untouched.epub")

        # Reserved for the annotation tests. Highlights are server-side
        # and shared (decision 7), so a book another test marks up would
        # carry those marks into this one. Nothing else may open it.
        EpubBuilder(
            title="Annotate Me",
            author="A Reader",
            chapters=3,
            paragraphs_per_chapter=4,
        ).build(self.library / "annotate-me.epub")

        # Reserved for the record editor. What a person says is locked
        # and outlives every rescan, so a book edited here stays edited
        # in every later run. Nothing else may assert on it.
        EpubBuilder(
            title="Edit Me",
            author="A Reader",
            description="What the file says about itself.",
        ).build(self.library / "edit-me.epub")

        # MOBI and AZW3 share a container that foliate sniffs rather
        # than trusting the extension — so the reader needed no change,
        # only the library did.
        MobiBuilder(
            title="A Kindle Book",
            authors=["Frank Herbert"],
            subjects=["Science Fiction"],
            published="1965-10-01",
            cover=jpeg(),
            # Long enough that there is a second page to turn to.
            text="<html><body>" + "".join(
                f"<p>Text. Paragraph {i} of a Kindle book, padded out so"
                " that pagination has real work to do.</p>"
                for i in range(40)) + "</body></html>",
        ).build(self.library / "kindle-book.mobi")

        # A comic: a zip of images, which foliate draws page by page.
        CbzBuilder(pages=6).build(
            self.library / "Zootopia 001 (2025) (digital) (Salem-Empire).cbz")

        # A book that was never zipped: 265 of the real library are
        # directories, and they were invisible until M8.
        EpubBuilder(
            title="Never Zipped",
            author="A Reader",
            chapters=3,
            paragraphs_per_chapter=4,
        ).build_unpacked(self.library / "Never Zipped.epub")

        # PDF: a different rendering model — pdf.js rasterises pages
        # rather than reflowing text, and runs its parser in a worker,
        # which nothing else here does.
        PdfBuilder(
            title=None,          # as most real ones are: no usable title
            author=None,
            pages=3,
            lines=["A page of a PDF book.", "Rendered by pdf.js."],
        ).build(self.library / "Herbert, Frank - A Pdf Book.pdf")

        # A scan whose only page is a JPEG 2000 image, as 17 real PDFs
        # carry their pictures. Nothing but pdf.spec.js opens it.
        PdfBuilder(
            title=None, author=None, pages=1,
            cover=jpx(), cover_filter="JPXDecode",
        ).build(self.library / "Scanned, A - A Jpx Scan.pdf")

        # A bookmark that points at something other than a page, as one
        # real encyclopaedia's does. Nothing but pdf.spec.js opens it.
        PdfBuilder(
            title=None, author=None, pages=2, broken_bookmark=True,
        ).build(self.library / "Marked, A - A Broken Bookmark.pdf")

        # Dutch, and saying nothing about it: `und` in its own OPF, as a
        # good part of the real library does. It is Dutch on the shelves
        # only because the startup scan read its words (§8.27).
        EpubBuilder(
            title="Het Stille Boek",
            author="Annie Verhoeven",
            language="und",
            chapters=2,
            paragraphs_per_chapter=6,
            prose=("Het was een koude avond in de stad en de kinderen liepen"
                   " naar huis. Ze hadden geen geld meer, maar ze waren niet"
                   " bang. Hij zei dat het niet zo ver was en dat ze er voor"
                   " het donker zouden zijn. Toen ze bij de brug kwamen, zag"
                   " ik dat er iets in het water lag."),
        ).build(self.library / "het-stille-boek.epub")

        EpubBuilder(
            title="Hostile Book",
            author="Test Author",
            scripted=True,
        ).build(self.library / "hostile.epub")

        self.env_file.write_text(
            ENV_TEMPLATE.format(port=self.PORT, library=self.library)
        )
        print(f"library: {self.library}")
        print(f"env:     {self.env_file}")


if __name__ == "__main__":
    TestLibrary(ROOT).build()
