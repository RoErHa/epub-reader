"""The badge strip at the top of README.md, and the counts behind it.

dlna-gateway's badges are hand-maintained strings, which is fine until
somebody adds a test and the number quietly stops being true. These are
generated from the suites themselves and **checked by a test**, so a
stale badge fails the build rather than misleading a reader — the rule
`tests/test_lint.py` already applies to the linter.

    .venv/bin/python tools/badges.py          # report, change nothing
    .venv/bin/python tools/badges.py --write  # rewrite the strip
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"

# The strip lives between these two markers so the rest of the README is
# never touched — and so a human can move it without breaking the writer.
BEGIN = "<!-- badges: generated by tools/badges.py -->"
END = "<!-- /badges -->"


class CountError(RuntimeError):
    """A suite could not be counted, and why."""


class TestCounts:
    """How many checks there are, counted the way each suite counts them
    rather than by grepping for `def test_` — parameterised cases and
    two browser projects both make the honest number bigger than the
    written one."""

    def unit(self) -> int:
        """pytest, collected but not run."""
        out = self._run([sys.executable, "-m", "pytest", "--collect-only",
                         "-q", "-p", "no:warnings"], "pytest")
        # `-q` reports one `path: N` line per file.
        counts = re.findall(r"^tests/\S+: (\d+)$", out, re.MULTILINE)
        if not counts:
            raise CountError("pytest collected nothing that could be counted")
        return sum(int(n) for n in counts)

    def browser(self) -> int:
        """Playwright, across every project — Chromium and WebKit both,
        because §10.5 is why the suite runs in two engines at all."""
        if not shutil.which("npx"):
            raise CountError("npx is not on this machine")
        out = self._run(["npx", "playwright", "test", "--list"], "playwright")
        found = re.search(r"^Total: (\d+) tests?", out, re.MULTILINE)
        if not found:
            raise CountError("playwright printed no total")
        return int(found.group(1))

    @staticmethod
    def _run(argv: list[str], what: str) -> str:
        try:
            result = subprocess.run(argv, cwd=ROOT, capture_output=True,
                                    text=True, timeout=300, check=False)
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise CountError(f"could not run {what}: {exc}") from exc
        return result.stdout + result.stderr


class BadgeStrip:
    """The markdown between the markers."""

    def __init__(self, unit: int, browser: int) -> None:
        self._unit = unit
        self._browser = browser

    @staticmethod
    def _quote(text: str) -> str:
        """shields.io wants its label URL-escaped; `-` and `_` are its own
        separators and must be doubled rather than percent-encoded."""
        return (text.replace("-", "--").replace("_", "__")
                    .replace(" ", "%20").replace("·", "%C2%B7")
                    .replace(",", "%2C").replace("+", "%2B"))

    SHIELDS = "https://img.shields.io/badge"

    @classmethod
    def _badge(cls, alt: str, slug: str, link: str) -> str:
        return f"[![{alt}]({cls.SHIELDS}/{slug}.svg)]({link})"

    def render(self) -> str:
        tests = self._quote(f"{self._unit:,} unit · {self._browser} browser")
        return "\n".join([
            BEGIN,
            self._badge("License: MIT", "License-MIT-blue", "LICENSE"),
            self._badge("Python 3.13+", "python-3.13%2B-blue",
                        "https://www.python.org/"),
            self._badge("Tests", f"tests-{tests}-brightgreen", "#code-quality"),
            self._badge("Lint: ruff",
                        "lint-ruff%20%C2%B7%200%20violations-brightgreen",
                        "#code-quality"),
            self._badge("Security policy", "security-policy-informational",
                        "SECURITY.md"),
            END,
        ])


class Readme:
    """README.md, and the one region of it this tool may touch."""

    def __init__(self, path: Path = README) -> None:
        self._path = path

    def current(self) -> str:
        text = self._path.read_text()
        start = text.find(BEGIN)
        end = text.find(END)
        if start == -1 or end == -1:
            raise CountError(
                f"{self._path.name} has no badge markers; add {BEGIN} and {END}")
        return text[start:end + len(END)]

    def write(self, strip: str) -> bool:
        """Returns whether anything changed."""
        current = self.current()
        if current == strip:
            return False
        text = self._path.read_text().replace(current, strip, 1)
        self._path.write_text(text)
        return True


def main(argv: list[str]) -> int:
    counts = TestCounts()
    strip = BadgeStrip(counts.unit(), counts.browser()).render()
    readme = Readme()
    if "--write" in argv:
        changed = readme.write(strip)
        print("Badges updated." if changed else "Badges were already right.")
        return 0
    same = readme.current() == strip
    print("Badges are current." if same else
          "Badges are STALE — run: .venv/bin/python tools/badges.py --write")
    return 0 if same else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
